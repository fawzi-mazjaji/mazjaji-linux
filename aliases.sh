# ---------- الهدية (دالة تنظيف المجلدات الفارغة) ----------
نظف-فارغ() {
    local target="${1:-.}"
    if [[ "$1" == "-h" ]] || [[ "$1" == "--help" ]]; then
        echo "الاستخدام: نظف-فارغ [--dry-run] [المسار]"
        echo "  --dry-run : عرض المجلدات التي سيتم حذفها فقط (بدون حذف فعلي)"
        echo "  المسار    : المجلد الذي سيتم البحث فيه (الافتراضي: المجلد الحالي)"
        return 0
    fi
    if [[ ! -d "$target" ]]; then
        echo "خطأ: المسار '$target' غير موجود"
        return 1
    fi
    echo "🔍 البحث عن مجلدات فارغة في: $target"
    if [[ "$1" == "--dry-run" ]]; then
        find "$target" -type d -empty -print
        echo "✅ انتهى العرض. لم يتم حذف أي شيء."
    else
        find "$target" -type d -empty -exec rmdir -v {} \;
        echo "✅ تم حذف جميع المجلدات الفارغة."
    fi
}
